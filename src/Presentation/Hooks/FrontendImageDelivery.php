<?php
/**
 * Deliver recorded variants with an original image fallback.
 *
 * @package KilobyteImageOptimizer
 */

declare(strict_types=1);

namespace Kilobyte\ImageOptimizer\Presentation\Hooks;

use Kilobyte\ImageOptimizer\Infrastructure\WordPress\WpAttachmentRepository;
use WP_HTML_Tag_Processor;

/**
 * Adds picture sources for local attachments whose variants are available.
 */
final class FrontendImageDelivery {

	/** @var WpAttachmentRepository */
	private WpAttachmentRepository $attachments;

	/** @var array<string, array<string, string>> */
	private array $paths = array();

	/** @var array<string, array<string, int>> */
	private array $widths = array();

	/** @var array<string, bool> */
	private array $available = array();

	/**
	 * @param WpAttachmentRepository $attachments Media storage.
	 */
	public function __construct( WpAttachmentRepository $attachments ) {
		$this->attachments = $attachments;
	}

	/**
	 * Register delivery hooks for rendered content and featured images.
	 *
	 * @return void
	 */
	public function register(): void {
		if ( is_admin() ) {
			return;
		}

		add_filter( 'the_content', array( $this, 'wrap_content_images' ), 20 );
		add_filter( 'wp_get_attachment_image', array( $this, 'wrap_attachment_image' ), 20, 2 );
		add_filter( 'post_thumbnail_html', array( $this, 'wrap_thumbnail' ), 20, 3 );
	}

	/**
	 * Wrap supported image tags in rendered content.
	 *
	 * @param string $html Rendered content.
	 * @return string
	 */
	public function wrap_content_images( string $html ): string {
		return $this->wrap_images( $html, 0 );
	}

	/**
	 * Wrap HTML generated by WordPress for a known attachment.
	 *
	 * @param string $html          Image HTML.
	 * @param int    $attachment_id Attachment ID.
	 * @return string
	 */
	public function wrap_attachment_image( string $html, int $attachment_id ): string {
		return $this->wrap_images( $html, $attachment_id );
	}

	/**
	 * Wrap a known featured image attachment.
	 *
	 * @param string $html          Featured image HTML.
	 * @param int    $post_id       Parent post ID.
	 * @param int    $attachment_id Attachment ID.
	 * @return string
	 */
	public function wrap_thumbnail( string $html, int $post_id, int $attachment_id ): string {
		return $this->wrap_images( $html, $attachment_id );
	}

	/**
	 * Process only standalone image tags. Existing pictures and raw HTML sections stay intact.
	 *
	 * @param string $html          Rendered HTML.
	 * @param int    $attachment_id Known attachment ID if available.
	 * @return string
	 */
	private function wrap_images( string $html, int $attachment_id ): string {
		if ( false === stripos( $html, '<img' ) ) {
			return $html;
		}

		$stats = get_option( WpAttachmentRepository::STATS_OPTION, array() );
		if ( empty( $stats['optimized_count'] ) ) {
			return $html;
		}

		$uploads = wp_get_upload_dir();
		$base    = untrailingslashit( $uploads['baseurl'] ?? '' ) . '/';
		$host    = wp_parse_url( $base, PHP_URL_HOST );
		if ( ! $host || ! in_array( $host, array( wp_parse_url( home_url(), PHP_URL_HOST ), wp_parse_url( site_url(), PHP_URL_HOST ) ), true ) ) {
			return $html;
		}

		$attributes = '(?:[^>"\']|"[^"]*"|\'[^\']*\')*';
		$updated    = preg_replace_callback(
			'~<!--.*?(?:-->|$)(*SKIP)(*FAIL)|<(picture|script|style|textarea|template)\b' . $attributes .
			'>.*?</\1\s*>(*SKIP)(*FAIL)|<img\b' . $attributes . '>|</?[a-z][a-z0-9:-]*\b' . $attributes . '>(*SKIP)(*FAIL)~is',
			function ( array $matches ) use ( $attachment_id, $base ): string {
				return $this->wrap_image( $matches[0], $attachment_id, $base );
			},
			$html
		);
		return $updated ?? $html;
	}

	/**
	 * Add a source set only when each original candidate has an available variant.
	 *
	 * @param string $html          Image HTML.
	 * @param int    $attachment_id Attachment ID when known.
	 * @param string $base          Uploads URL ending in a slash.
	 * @return string
	 */
	private function wrap_image( string $html, int $attachment_id, string $base ): string {
		$tag = new WP_HTML_Tag_Processor( $html );
		if ( ! $tag->next_tag( 'IMG' ) || null !== $tag->get_attribute( 'data-wp-on--load' ) ) {
			return $html;
		}
		if ( $attachment_id <= 0 && preg_match( '/(?:^|\s)wp-image-(\d+)(?:\s|$)/', (string) $tag->get_attribute( 'class' ), $match ) ) {
			$attachment_id = (int) $match[1];
		}

		$src = $tag->get_attribute( 'src' );
		if ( $attachment_id <= 0 || ! is_string( $src ) || 0 !== strpos( $src, $base ) ) {
			return $html;
		}

		$key = get_current_blog_id() . ':' . $attachment_id;
		if ( ! isset( $this->paths[ $key ] ) ) {
			$record               = $this->attachments->get_record( $attachment_id );
			$url                  = wp_get_attachment_url( $attachment_id );
			$this->paths[ $key ]  = $record && is_string( $url ) && 0 === strpos( $url, $base )
				? $this->attachments->variant_paths( $attachment_id, $record )
				: array();
			$this->widths[ $key ] = $record ? $record->variant_widths() : array();
		}
		$variants = $this->paths[ $key ];
		if ( empty( $variants ) ) {
			return $html;
		}

		$srcset = $tag->get_attribute( 'srcset' );
		$sizes  = $tag->get_attribute( 'sizes' );
		$inputs = is_string( $srcset ) && '' !== trim( $srcset ) ? preg_split( '/\s*,\s*/', trim( $srcset ) ) : array( $src );
		$root   = $this->attachments->uploads_root();
		$mapped = array();
		$mime   = '';

		foreach ( $inputs as $input ) {
			$parts = preg_split( '/\s+/', trim( $input ), 2 );
			$url   = $parts[0];
			if ( 0 !== strpos( $url, $base ) || null === $root ) {
				return $html;
			}
			$relative = rawurldecode( substr( $url, strlen( $base ) ) );
			$path     = $variants[ $relative ] ?? '';
			if ( '' === $path ) {
				return $html;
			}
			$file = $root . $path;
			if ( ! isset( $this->available[ $file ] ) ) {
				$this->available[ $file ] = null !== $this->attachments->resolve_safe_upload_file( $file );
			}
			if ( ! $this->available[ $file ] ) {
				return $html;
			}

			$type       = wp_check_filetype( $path )['type'];
			$descriptor = $parts[1] ?? '';
			if ( preg_match( '/^\d+w$/D', $descriptor ) ) {
				if ( ! isset( $this->widths[ $key ][ $path ] ) ) {
					$dimensions                    = wp_getimagesize( $file );
					$this->widths[ $key ][ $path ] = is_array( $dimensions ) ? (int) $dimensions[0] : 0;
				}
				$width = $this->widths[ $key ][ $path ];
				if ( $width <= 0 ) {
					return $html;
				}
				$descriptor = $width . 'w';
				if ( isset( $mapped[ $descriptor ] ) ) {
					continue;
				}
			} elseif ( '' !== $descriptor && ! preg_match( '/^\d+(?:\.\d+)?x$/D', $descriptor ) ) {
				return $html;
			}
			if ( ! is_string( $type ) || ( '' !== $mime && $type !== $mime ) ) {
				return $html;
			}
			$mime                  = $type;
			$mapped[ $descriptor ] = $base . implode( '/', array_map( 'rawurlencode', explode( '/', $path ) ) ) . ( '' !== $descriptor ? ' ' . $descriptor : '' );
		}

		if ( empty( $mapped ) ) {
			return $html;
		}
		return sprintf(
			'<picture><source type="%s" srcset="%s"%s>%s</picture>',
			esc_attr( $mime ),
			esc_attr( implode( ', ', $mapped ) ),
			is_string( $sizes ) && '' !== $sizes ? ' sizes="' . esc_attr( $sizes ) . '"' : '',
			$html
		);
	}
}
